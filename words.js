// A word your partner taught you comes first, one per day from the day it was added;
// otherwise today's word from the list. `taught` items need a `day` (YYYY-MM-DD, local).
function wordOfTheDay(dayKey, lang, taught) {
  const list = WORDS[lang];
  if (!list) return null;
  const plusDay = (k) => new Date(Date.parse(k + "T12:00:00Z") + 86400000).toISOString().slice(0, 10);
  let next = "";
  const queue = (taught || []).filter((w) => w.lang === lang).slice()
    .sort((a, b) => a.day.localeCompare(b.day) || String(a.created_at).localeCompare(String(b.created_at)));
  for (const w of queue) {
    const d = w.day > next ? w.day : next;
    if (d === dayKey) return { lang, word: w.word, meaning: w.meaning, example: w.example || "", translation: "", from: w.added_by, id: w.id };
    next = plusDay(d);
  }
  const n = Math.floor(Date.parse(dayKey + "T12:00:00Z") / 86400000);
  const e = list[((n % list.length) + list.length) % list.length];
  return { lang, word: e[0], meaning: e[1], example: e[2] || "", translation: e[3] || "", from: null };
}

